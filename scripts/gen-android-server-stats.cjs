#!/usr/bin/env node
"use strict";
/**
 * Generates infrastructure/android/serverStatsCommands.generated.ts by EVALUATING the Linux
 * stats shell commands straight out of the desktop implementation
 * (electron/bridges/sshBridge/sessionOps.cjs), so the Android build runs the exact same probes.
 * GPU / disk-IO probes are replaced with empty assignments (not ported to Android yet).
 * Re-run after changing the desktop commands:  node scripts/gen-android-server-stats.cjs
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const root = path.resolve(__dirname, "..");
const srcPath = path.join(root, "electron/bridges/sshBridge/sessionOps.cjs");
const src = fs.readFileSync(srcPath, "utf8");

function slice(startMarker, endMarker) {
  const a = src.indexOf(startMarker);
  const b = src.indexOf(endMarker, a);
  if (a < 0 || b < 0) throw new Error(`markers not found: ${startMarker} .. ${endMarker}`);
  return src.slice(a, b);
}

// Helpers copied verbatim from the desktop source
const watchdog = slice("function withRemoteWatchdog(", "function withPosixRemoteWatchdog(")
  || "";
const watchdogBody = (() => {
  const a = src.indexOf("function withRemoteWatchdog(");
  // up to the next top-level "function " at column 0 after it
  const rest = src.slice(a + 10);
  const m = rest.search(/\n(?:async )?function |\n    function withPosixRemoteWatchdog|\nconst |\nmodule\./);
  return src.slice(a, a + 10 + (m < 0 ? rest.length : m));
})();

const segment = slice("const linuxDiskAwk = String.raw", "// Dropbear rejects command requests larger");

const quoteShellArg = (v) => `'${String(v).replace(/'/g, `'\\''`)}'`;

const factory = vm.runInNewContext(`(function(session, GPU_ASSIGNMENT, DISK_IO_ASSIGNMENT, PARTITION_IO_ASSIGNMENT, withPosixRemoteWatchdog){
  ${segment}
  return { linuxStatsCommand, linuxDiskStatsCommand };
})`);

const ctx = {};
vm.runInNewContext(`${watchdogBody}; this.withRemoteWatchdog = withRemoteWatchdog;`, Object.assign(ctx, { quoteShellArg }));
const withPosix = (command, ms) => `exec sh -c ${quoteShellArg(ctx.withRemoteWatchdog(command, ms))}`;

const { linuxStatsCommand, linuxDiskStatsCommand } = factory(
  { _monitorStats: false },
  'gpustat=""',
  'diskio=""',
  'partitionio=""; diskmounts=""',
  withPosix,
);

const guard = `[ "$(uname -s 2>/dev/null)" = "Linux" ] || { echo "UNSUPPORTED_OS:$(uname -s 2>/dev/null)"; exit 0; }`;
const statsCmd = withPosix(`${guard}; ${linuxStatsCommand}`, 10000);

const out = `// AUTO-GENERATED by scripts/gen-android-server-stats.cjs — do not edit by hand.
// Source of truth: electron/bridges/sshBridge/sessionOps.cjs (Linux stats probes).
export const LINUX_STATS_COMMAND: string = ${JSON.stringify(statsCmd)};
export const LINUX_DISK_COMMAND: string = ${JSON.stringify(linuxDiskStatsCommand)};
`;
fs.writeFileSync(path.join(root, "infrastructure/android/serverStatsCommands.generated.ts"), out);
console.log("stats bytes:", Buffer.byteLength(statsCmd), "disk bytes:", Buffer.byteLength(linuxDiskStatsCommand));
